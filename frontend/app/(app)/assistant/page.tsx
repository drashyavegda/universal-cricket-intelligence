'use client';
import { useState } from 'react';
import Link from 'next/link';
import { apiPost } from '@/lib/client/api';
import { Alert, Badge, Button, Card, KV, Loading, PageHeader } from '@/components/ui';
import { MessageSquare, Send, ShieldAlert } from 'lucide-react';

interface Answer {
  query: string;
  parsed: { intent: string; interpretation: string; confidence: number; language: string; players: string[]; role: string | null; maxAge: number | null };
  answer: string; evidence: { label: string; value: string; source?: string }[];
  actions: { label: string; href: string }[]; followUps: string[];
  confirmRequired: boolean; confirmationPrompt?: string; aiMode?: string; aiNote?: string;
  blocked?: boolean; redactions?: number;
}
interface Turn { role: 'user' | 'assistant'; content: string; data?: Answer }

const SUGGESTIONS = [
  'Find the best young batters under 21',
  'Compare three fast bowlers',
  'Show economical spinners',
  'What is the auction value of my top target?',
  'Which pitch suits spin in Chennai?',
  'Explain the ranking of the top young talent',
  'Generate a report for the top prospect',
];

export default function AssistantPage() {
  const [input, setInput] = useState('');
  const [turns, setTurns] = useState<Turn[]>([]);
  const [busy, setBusy] = useState(false);
  const [confirming, setConfirming] = useState<string | null>(null);

  const ask = async (query: string, isConfirm = false) => {
    if (!query.trim()) return;
    setBusy(true);
    setTurns((t) => [...t, { role: 'user', content: query }]);
    setInput('');
    try {
      const res = await apiPost<Answer>('/api/assistant', { query: isConfirm ? `${query} — confirmed, proceed` : query });
      setTurns((t) => [...t, { role: 'assistant', content: res.answer, data: res }]);
      if (res.confirmRequired) setConfirming(query);
    } catch (e) {
      setTurns((t) => [...t, { role: 'assistant', content: `Error: ${(e as Error).message}` }]);
    } finally { setBusy(false); }
  };

  return (
    <div className="space-y-4">
      <PageHeader title="AI Assistant" description="Natural-language analytics. The parser converts your question into a structured query, runs the deterministic engine, then optionally has a model narrate the result. Numbers are never generated by the model.">
        <Badge tone="green">Rule-based parser + optional LLM narration</Badge>
      </PageHeader>

      <div className="grid gap-4 lg:grid-cols-3">
        <Card className="lg:col-span-2" title="Conversation" subtitle="Follow-ups keep the workspace context">
          <div className="max-h-[520px] space-y-3 overflow-auto pr-1">
            {turns.length === 0 && (
              <div className="rounded-lg border border-dashed border-line p-4">
                <div className="text-[12px] text-slate-200">Ask anything about the workspace data.</div>
                <div className="mt-2 flex flex-wrap gap-1.5">
                  {SUGGESTIONS.map((s) => <button key={s} onClick={() => ask(s)} className="rounded-full border border-line px-2.5 py-1 text-[10.5px] text-slateink-300 hover:border-turf-500/40 hover:text-white">{s}</button>)}
                </div>
              </div>
            )}
            {turns.map((t, i) => (
              <div key={i} className={t.role === 'user' ? 'flex justify-end' : ''}>
                <div className={`max-w-[92%] rounded-xl px-3 py-2 text-[12px] leading-relaxed ${t.role === 'user' ? 'bg-turf-500/15 text-turf-100 ring-1 ring-turf-500/25' : 'border border-line bg-ink-900/60 text-slate-200'}`}>
                  <div>{t.content}</div>
                  {t.data && (
                    <>
                      <div className="mt-2 flex flex-wrap gap-1">
                        <Badge tone="slate">intent: {t.data.parsed.intent}</Badge>
                        <Badge tone="slate">confidence {(t.data.parsed.confidence * 100).toFixed(0)}%</Badge>
                        {t.data.aiMode && <Badge tone={t.data.aiMode === 'live' ? 'green' : 'gold'}>ai: {t.data.aiMode}</Badge>}
                        {t.data.blocked && <Badge tone="red">guard triggered</Badge>}
                      </div>
                      {t.data.evidence.length > 0 && (
                        <div className="mt-2 space-y-1 border-t border-line/60 pt-2">
                          {t.data.evidence.slice(0, 6).map((e, k) => (
                            <div key={k} className="text-[10.5px]"><span className="text-slateink-400">{e.label}:</span> <span className="text-slate-200">{e.value}</span>{e.source && <span className="text-slateink-600"> · {e.source}</span>}</div>
                          ))}
                        </div>
                      )}
                      {t.data.actions.length > 0 && (
                        <div className="mt-2 flex flex-wrap gap-1.5">
                          {t.data.actions.map((a) => <Link key={a.href} href={a.href} className="rounded border border-turf-500/30 px-2 py-0.5 text-[10px] text-turf-300 hover:bg-turf-500/10">{a.label}</Link>)}
                        </div>
                      )}
                      {t.data.confirmRequired && (
                        <div className="mt-2">
                          <Alert tone="warn">{t.data.confirmationPrompt}</Alert>
                          <Button size="xs" className="mt-1.5" onClick={() => ask(t.data!.query, true)}>Confirm and proceed</Button>
                        </div>
                      )}
                      {t.data.aiNote && <div className="mt-1.5 text-[9.5px] text-slateink-500">{t.data.aiNote}</div>}
                    </>
                  )}
                </div>
              </div>
            ))}
            {busy && <Loading label="Working" />}
          </div>
          <div className="mt-3 flex gap-2">
            <input className="input" placeholder="Ask a question…" value={input} onChange={(e) => setInput(e.target.value)} onKeyDown={(e) => e.key === 'Enter' && ask(input)} />
            <Button onClick={() => ask(input)} disabled={busy}><Send size={14} />Ask</Button>
          </div>
          {confirming && <div className="mt-2 text-[10px] text-slateink-500">A consequential action is waiting for explicit confirmation. Nothing has been written yet.</div>}
        </Card>

        <div className="space-y-4">
          <Card title="Safety & honesty">
            <div className="space-y-2 text-[10.5px] leading-relaxed text-slateink-400">
              <div className="flex items-start gap-1.5"><ShieldAlert size={12} className="mt-0.5 text-ember-400" />Prompt-injection patterns in your question are neutralised and the request is refused, not executed.</div>
              <div>• Consequential actions (saving reports, approvals) always require confirmation.</div>
              <div>• The narration layer receives only pre-computed numbers and is instructed not to invent statistics.</div>
              <div>• Without an AI key, replies are deterministic templates labelled as demo narration.</div>
            </div>
          </Card>
          <Card title="How parsing works">
            <KV items={[
              { k: 'Intents', v: 'rank · compare · explain · auction · pitch · workload · prediction · squad · report' },
              { k: 'Multilingual', v: 'English, Hindi and Gujarati keyword sets' },
              { k: 'Voice', v: 'Browser speech input is available in the UI layer; this build ships typed input' },
              { k: 'History', v: 'Stored per session in the browser (not persisted server-side)' },
            ]} />
          </Card>
          <Card title="Try a follow-up">
            <div className="flex flex-wrap gap-1.5">
              {SUGGESTIONS.slice(2).map((s) => <button key={s} onClick={() => ask(s)} className="rounded-full border border-line px-2 py-0.5 text-[10px] text-slateink-300 hover:border-turf-500/40">{s}</button>)}
            </div>
          </Card>
        </div>
      </div>
      <div className="flex items-center gap-2 text-[10.5px] text-slateink-500"><MessageSquare size={12} /> The assistant never performs a write action without an explicit confirmation step.</div>
    </div>
  );
}
